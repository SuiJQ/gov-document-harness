def main() -> int:
    块 = re.split(r"^### ", 台账.read_text(encoding="utf-8"), flags=re.M)[1:]
    行 = ["序号\t决策号\t性质\t状态\t去向\t标题"]
    序 = 0
    for b in 块:
        首 = b.split("\n")[0].strip()
        m = 块正则.match(首)
        if m:
            号, 标题 = m.group(1), m.group(2).strip()
            if 号 in 规则集:
                性 = "规则"
            elif 号 in 缺陷已修:
                性 = "经历·已解决"
            elif 号 in 缺陷留账:
                性 = "经历·未解决"
            elif 号 in 快照:
                性 = "快照"
            elif 号 in 作废:
                性 = "临时决定"
            elif 号 in 欠账:
                性 = "欠账"
            elif 号 in 复测改判:
                性 = "经历·已解决"
            elif 号 in 经历一次性:
                性 = "经历·已解决"
            elif 号 in 新立规则:
                性 = "规则"
            elif 号[2:].isdigit() and 297 <= int(号[2:]) <= 378:
                # 这批是原先无编号的经验与经历，补号后已落进台账。
                # 定性在当初**读完全文逐条判**时定下（见 `序判`），不是按标题猜的，
                # 故直接查表，不再重新判一遍。
                性 = 序判.get(int(号[2:]) - 296, "经历·已解决")
            else:
                性 = "?"
        else:
            序 += 1
            号 = f"D-{296 + 序:03d}"
            标题 = 首
            性 = 序判.get(序, "经历·已解决")
        行.append(f"{len(行)}\t{号}\t{性}\t{状态(性)}\t{去向(性)}\t{标题[:54]}")
    出.write_text("\n".join(行) + "\n", encoding="utf-8")
    cnt = collections.Counter(l.split("\t")[2] for l in 行[1:])
    未定 = [l.split("\t")[1] for l in 行[1:] if l.split("\t")[2] == "?"]
    print(f"共 {len(行) - 1} 条 → {出.relative_to(根)}")
    for k, v in cnt.most_common():
        print(f"  {v:>4}  {k}")
    if 未定:
        print(f"未定性：{未定}")
    未 = [l.split("\t")[1] for l in 行[1:] if l.split("\t")[3].startswith("未解决")]
    print(f"未解决（{len(未)}）：{未}")
    return 0


