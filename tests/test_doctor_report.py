"""doctor 健康自检（D-246）。

## 这处原先只有 56%，因为「报告」是它最重要的职责却没人测

自检的全部价值在于**失败时告诉用户三件事**（D-027）：
失败在哪一步、报了什么错、用户可以怎么处理。

只测「全通过」的话，这三件事一个都没验证——
而它们恰恰是用户看得见的部分。
"""

from __future__ import annotations

import io

from zhengtong.presentation.doctor import (
    自检项,
    跑自检,
    打印自检,
)


class Test报告内容:
    def test_全通过的报告(self) -> None:
        结果 = 跑自检(
            探测=(
                自检项("网络连通", True, "0.76 秒"),
                自检项("鉴权", True),
            )
        )
        assert 结果.全通过
        文本 = 结果.报告()
        assert "网络连通" in 文本 and "鉴权" in 文本
        assert "全部通过" in 文本

    def test_失败项报出三件事(self) -> None:
        """**D-027 的核心判据**：失败在哪、报了什么、怎么处理。

        缺任何一件，用户都只能干瞪眼。
        """
        结果 = 跑自检(
            探测=(
                自检项("网络连通", True),
                自检项("鉴权", False, "HTTP 401", "检查 API key 是否填错"),
            )
        )
        文本 = 结果.报告()
        assert "鉴权" in 文本, "没说是哪一项失败"
        assert "HTTP 401" in 文本, "没报出错误内容"
        assert "检查 API key" in 文本, "没告诉用户怎么处理"

    def test_全通过时不列处置(self) -> None:
        结果 = 跑自检(探测=(自检项("网络连通", True, "0.76 秒", "不该出现"),))
        文本 = 结果.报告()
        assert "不该出现" not in 文本, "全通过却列了处置"

    def test_行与报告一致(self) -> None:
        """`行()` 与 `报告()` 不能各说各话——
        接口层（打印）走一个、无界面走另一个时最容易分叉。"""
        结果 = 跑自检(探测=(自检项("网络连通", False, "超时", "换个网"),))
        for 行 in 结果.行():
            assert 行 in 结果.报告(), f"行 {行!r} 不在报告里"


class Test字体只提示不阻止:
    def test_字体不合格不影响通过(self) -> None:
        """**用户明确：字体不合格仅提示、不阻止运行。**

        若它算失败，终端字形不齐的用户就被挡在门外——
        而那台机器完全能跑出正确结果。
        """
        结果 = 跑自检(探测=(), 字体="终端不支持中文字形")
        assert 结果.全通过, "字体问题竟判为失败——用户明确说仅提示"
        assert "中文字形" in 结果.报告(), "字体提示没出现在报告里"

    def test_字体通过时也要报告(self) -> None:
        结果 = 跑自检(探测=(自检项("网络连通", True),), 字体="字体正常")
        assert "字体正常" in 结果.报告()

    def test_无字体信息时不算一项(self) -> None:
        """没探测就不该凭空多一项——
        否则界面上会出现一条来源不明的「字体」行。"""
        结果 = 跑自检(探测=(自检项("网络连通", True),))
        assert len(结果.项) == 1, f"项数不对：{[项.名称 for 项 in 结果.项]}"


class Test打印:
    def test_打印到指定流(self) -> None:
        """打印走传入的流，**不污染 stdout**——
        否则无界面模式下会串到别处去。"""
        缓冲 = io.StringIO()
        打印自检(跑自检(探测=(自检项("网络连通", True),)), 流=缓冲)
        assert "网络连通" in 缓冲.getvalue()

    def test_打印失败报告也完整(self) -> None:
        缓冲 = io.StringIO()
        打印自检(
            跑自检(探测=(自检项("鉴权", False, "HTTP 401", "检查 key"),)), 流=缓冲
        )
        文本 = 缓冲.getvalue()
        assert "HTTP 401" in 文本 and "检查 key" in 文本

    def test_报告以换行结尾(self) -> None:
        """少一个换行，调用方拼进日志就会与下一行黏在一起。"""
        缓冲 = io.StringIO()
        打印自检(跑自检(探测=(自检项("网络连通", True),)), 流=缓冲)
        assert 缓冲.getvalue().endswith("\n"), "报告没以换行结尾"


class Test失败项视图:
    def test_失败项可单独取(self) -> None:
        结果 = 跑自检(
            探测=(
                自检项("网络连通", False, "超时", "换网"),
                自检项("鉴权", True),
                自检项("模型调用", False, "空正文", "换个模型"),
            )
        )
        assert [项.名称 for 项 in 结果.失败项] == ["网络连通", "模型调用"]
        assert not 结果.全通过

    def test_多个失败都列处置(self) -> None:
        结果 = 跑自检(
            探测=(
                自检项("网络连通", False, "超时", "换个网络环境"),
                自检项("鉴权", False, "401", "检查 API key"),
            )
        )
        文本 = 结果.报告()
        assert "换个网络环境" in 文本 and "检查 API key" in 文本
        assert "2 项未通过" in 文本, f"未说清有几项失败：{文本}"


class Test不测速:
    def test_只探测不测速(self) -> None:
        """**用户明确：不提供独立测速按钮。**

        探测是「能不能用」的二元判断。
        真报出「延迟 0.76 秒」会被用户当成性能承诺——
        而那个数字随机器负载剧烈波动，不作数。
        """
        结果 = 跑自检(探测=(自检项("网络连通", True, "延迟 0.76 秒"),))
        文本 = 结果.报告()
        # 详情可以带耗时（那是给排障看的），
        # 但报告**不得**把它列成一项指标
        assert "项未通过" not in 文本
        assert len(结果.项) == 1