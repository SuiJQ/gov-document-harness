"""**估算口径的契约测试** —— 对真实 `estimate.py` 的断言。

## 这个文件为什么从「规格」变成了「实检」

初版（本文件上一版）只把系数写成**本地常量**加断言，
并在文末 `pytest.skip("第 6 步 estimate.py 落地后改为实检")`。
那时 `estimate.py` 不存在，于是它是一份可执行的规格说明。

第 9 步已落地 `services/context/estimate.py`，故本文件改为
**直接调用真实实现**：断言打到 `估算文本` 与 `触发阈值` 上，
而不是打到本文件自己写的 `_估算汉字数` 上。

**为什么必须改**：若继续断言本地常量，那么真实现被改成 `×0.9`
（就是 D-077 记录的那次误改）时，本文件仍然全绿——
一份管不住口径漂移的契约测试等于没有。

## 三条不可让步的关系

| 口径 | 系数 | 相对实测 |
|---|---|---|
| 汉字（D-025 基线） | 每字 0.625 token | **高估 24%**，方向正确 |
| 非汉字 | 每字符 0.5 token | 保守，方向一致 |
| D-053「128K ≈ 64000 汉字」 | 每字 0.5 token | 实测口径 |

**高估是特性不是缺陷**（D-077）：估算的作用不是「算准」而是「提前示警」，
撞上限的代价远高于多压缩一次。
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from zhengtong.services.context.estimate import (
    估算文本,
    汉字除数,
    触发比例,
    触发阈值,
    非汉字除数,
)

#: D-025 的两组实测数据。任何时候改系数，都该拿这两组回归。
实测样本: tuple[tuple[int, int], ...] = (
    (16_000, 8_064),
    (60_000, 30_066),
)


def _汉字串(字数: int) -> str:
    return "国" * 字数


# ═══ 一、口径必须是高估而非低估 ═══


@pytest.mark.parametrize(("汉字数", "实测token"), 实测样本)
def test_估算须高于实测(汉字数: int, 实测token: int) -> None:
    """**高估是特性，不是缺陷**。

    若某天这个断言失败（估算变成等于或低于实测），说明有人
    把系数调「准」了——但那样会**更晚触发压缩**，而撞上下文上限
    的代价（请求被拒、整轮白跑）远高于多压缩一次。

    D-025 原话：「宁可压缩勤一点，不可撞上限」。
    """
    估算 = 估算文本(_汉字串(汉字数))
    assert 估算 >= 实测token, (
        f"{汉字数} 汉字实测 {实测token} token，估算 {估算} —— 变成了低估，撞上限前就发现不了了"
    )


def test_高估幅度须在合理区间() -> None:
    """高估 24% 是有意为之，但**不是无限高估**。

    高估过头同样有害：会毫无必要地丢上下文，
    而 D-039 规定了「绝不丢弃」的字段——丢多了等于变相违反。
    故给一个上限，卡住「为了保险改成 ÷1」这类改动。
    """
    高估比 = (估算文本(_汉字串(60_000)) / 30_066) - 1
    assert 0 < 高估比 < 0.35, f"高估 {高估比:+.1%} 超出有意区间（0~35%）"


def test_汉字除数仍是16而非09() -> None:
    """D-077 教训的定点守卫。

    曾据「中文 0.6–1.0 token/字」的通用经验把 ÷1.6 误判为低估、改成 ×0.9，
    事后证明 ×0.9 比实测**保守 79%**，会无谓地频繁触发压缩。
    这条断言把那个具体错误钉死——它是本文件里唯一一条
    「直接断言某个字面值」的测试，故单独成条而非混在关系断言里。
    """
    assert 汉字除数 == pytest.approx(1.6), f"汉字除数被改成了 {汉字除数}——见 D-077"


# ═══ 二、D-053 的口径必须与估算侧对齐 ═══


def test_D053的汉字上限须与估算口径自洽() -> None:
    """**架构 §7.2 明写「实施时需对齐」，这条就是那个对齐**。

    D-053 说「128K ≈ 64000 汉字」，取的是每汉字 0.5 token
    （即 D-025 的实测值）。而估算侧按 0.625 算。

    两者**不一致是允许的**，但必须是**已知且有向的**：
    估算侧更保守（128K 按估算只装 81,920 汉字，比 D-053 的 64,000 宽）。
    方向反了才是 bug——那会让 D-053 的说法反过来成为更宽松的承诺，
    调用方若照它准备材料，估算就会在材料已经装不下时才触发压缩。

    故此处断言的是**方向**：估算口径下可容纳的汉字数 ≥ D-053 的说法。
    """
    上下文容量 = 128 * 1024  # token
    D053_说法 = 64_000
    估算侧 = int(上下文容量 * 汉字除数)
    assert 估算侧 >= D053_说法, (
        f"估算侧只装得下 {估算侧} 汉字，比 D-053 的 {D053_说法} 还少 —— "
        f"方向反了：估算比文档承诺更严格，会在材料装不下时才报警"
    )


def test_D053与实测同源() -> None:
    """D-053 的 0.5 与 D-025 的实测 0.504 同源，不是另一个数。

    若有人把 D-053 也改成按 0.625 算，两个数字就都指向估算值了，
    「对齐」就变成了「互相抄」，失去互相印证的意义。
    """
    实测每字 = 实测样本[0][1] / 实测样本[0][0]
    assert 0.45 < 实测每字 < 0.55, f"D-025 实测每字 {实测每字:.3f}，不该被改动"
    assert abs(128 * 1024 * 实测每字 - 64_000) / 64_000 < 0.05, (
        "D-053 的『128K ≈ 64000 汉字』应与 D-025 实测同源"
    )


# ═══ 三、非汉字侧同样要保守 ═══


def test_非汉字须高估() -> None:
    """英文与代码每 token 约 4 字符，÷2 是保守值。"""
    assert 估算文本("a" * 4_000) >= 1_000


def test_非汉字高估幅度须合理() -> None:
    """÷2 相对精确值 ÷4 高估 100%——这个幅度偏大，但方向正确。

    这里只锁「不改成低估」：英文材料若按 ÷4 估，
    同一段代码会晚一半才触发压缩。
    """
    精确 = 4_000 / 4
    估算 = 估算文本("a" * 4_000)
    assert 估算 > 精确, "非汉字侧若比精确值还低，方向就反了"


def test_中英混排分开算() -> None:
    """汉字与非汉字**分开算**，且**分桶各自截断**。

    注意：混排结果**不等于**两侧各自单独估算再相加——
    `int()` 是分桶截断的：500 汉字得 312，而 1000 汉字得 625。
    本条断言的是分桶后的精确值，而非「可加性」。

    真正要防的退化是「有人图省事改成总字符数 ÷ 单一系数」，
    故另断言混排结果与那种朴素算法**不相等**。
    """
    混排 = 估算文本(_汉字串(500) + "a" * 500)
    按桶 = int(500 / 汉字除数) + int(500 / 非汉字除数)
    assert 混排 == 按桶, f"混排应分桶估算后相加，实得 {混排}，期望 {按桶}"

    朴素单系数 = int(1_000 / 非汉字除数)
    assert 混排 != 朴素单系数, "混排被算成了单一系数——中文部分没按汉字系数算"


def test_空串估为零() -> None:
    assert 估算文本("") == 0


