"""检索测试用的**可判定语料**。

## 为什么必须造语料，不能拿几篇样本凑合

判据是「top-k 召回 ≥95%」。**这个数字要有意义，前提是每条查询
都有唯一可判定的正确答案**——否则「召回」无从计算，
只能靠人看几眼说「还行」，那不叫判据。

故本模块造两类语料：

| 类型 | 构造 | 考察 |
|---|---|---|
| **探针语料** | 第 i 篇埋唯一关键词 `词{i}只在此篇` | 精确召回：能不能找到那唯一一篇 |
| **干扰语料** | 多篇共享高频词，靠**区分词**定胜负 | 排序质量：加权后 top-1 是不是对的 |

**只测第一类是自欺**：唯一关键词谁都能找到，哪怕检索层退化成
「返回全部候选」也照样 100% 召回。第二类才逼出排序能力。

## 语料里的词必须像公文

高频词用「通知」「批复」「报告」这类真公文词（架构 §7.3：
"通知""报告""请示""批复""通报"是公文最高频检索词），
不是 `foo` `bar`——**真实词频分布是排序权重的输入**，
用无意义字符串测出来的分数不代表真公文的分数。
"""

from __future__ import annotations

#: 公文高频词，做干扰项用（架构 §7.3 列举的五个）。
高频词: tuple[str, ...] = ("通知", "批复", "报告", "请示", "通报")

#: 探针语料的篇数（`探针语料()` 的默认值）。
探针篇数: int = 60


def 探针词(序号: int) -> str:
    """第 `序号` 篇的唯一关键词。**与 `探针语料` 必须同源**——
    两处各写一遍，语料一改判据就悄悄失效了。"""
    return f"独{序号:03d}词"


def 探针语料(篇数: int = 探针篇数) -> tuple[tuple[str, str], ...]:
    """每篇埋一个**只在此篇出现**的关键词。

    返回 `(ref, 正文)` 序列。`ref` 是条目引用（检索结果用它定位）。
    """
    条目: list[tuple[str, str]] = []
    for i in range(篇数):
        词 = 探针词(i)
        正文 = (
            f"关于{高频词[i % len(高频词)]}事项的{词}说明。"
            f"本篇讨论的主题是{词}，相关工作包括推进{词}落地。"
            f"现将有关情况报告如下，请予审阅。"
        )
        条目.append((f"doc-{i:03d}", 正文))
    return tuple(条目)


def 干扰语料(篇数: int = 20) -> tuple[tuple[str, str], ...]:
    """**每篇都含全部高频词**，只有区分词不同。

    这是真正考验排序的形态：查 `通知` 时每篇都能召回，
    分数应当由**区分词的权重**拉开差距——
    若排序退化成「按插入顺序返回」，top-1 就是错的。

    **ref 前缀用 `noise-` 而非 `doc-`**：与探针语料撞号会让
    `(查询, 期望 ref)` 的映射指向两篇不同的文档，
    召回率就成了拿 A 的答案查 B。**ref 唯一是检索层的基本契约。**
    """
    条目: list[tuple[str, str]] = []
    for i in range(篇数):
        区分 = f"区分{i:03d}"
        正文 = f"关于{区分}事项的通知。为做好{区分}相关工作，现将有关情况报告如下，请审阅并批复。"
        条目.append((f"noise-{i:03d}", 正文))
    return tuple(条目)


def 混合语料() -> tuple[tuple[str, str], ...]:
    """探针 + 干扰合一：既有唯一可判定的答案，也有排序压力。"""
    return 探针语料(60) + 干扰语料(20)


def 查询与答案(条目: tuple[tuple[str, str], ...]) -> tuple[tuple[str, str], ...]:
    """从探针篇推出 `(查询, 期望 ref)`。

    **期望 ref 由命名规则直接算出，不解析正文、不看检索结果**——
    否则就是循环论证：拿检索的输出当标准答案，召回率永远 100%。
    """
    答案: list[tuple[str, str]] = []
    for ref, _ in 条目:
        # **必须认前缀**：只按序号判会把 `noise-019`（干扰篇，序号也是 19）
        # 当成探针篇，于是拿干扰篇的 ref 当标准答案去查——
        # 期望答案本身就错了，召回率随之失去意义。
        if not ref.startswith("doc-"):
            continue
        序号 = int(ref.split("-")[1])
        if 序号 < 探针篇数:
            答案.append((探针词(序号), ref))
    return tuple(答案)
