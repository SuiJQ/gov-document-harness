"""Token 估算。**估算公式只允许存在于本文件一处**（架构 §7.2）。

## 为什么估算必须和真实用量分开（D-077）

| 用途 | 用哪个 | 理由 |
|---|---|---|
| 压缩触发判定（85% 阈值） | **本文件的保守估算** | 早触发优于晚发现 |
| 界面展示用量 | API 返回的真实值 | 用户看的是实际消耗 |
| 门禁 token 台账（D-031） | 真实值 | 耗时预估须基于事实 |

理由：真实值只有请求发出之后才知道，那时窗口已满——
**估算的作用不是「算准」，而是「提前示警」**，
故不能用真实值做触发判定。

## 系数来自实测，不是拍脑袋（D-025）

D-025 实测两组：16,000 汉字 → 8,064 token（每字 0.504）；
60,000 汉字 → 30,066（每字 0.501）。即每汉字约 0.5 token。

本文件按 **汉字 ÷ 1.6**（每字算 0.625），比实测**高估 24%**。

> **⚠️ 别改成 ×0.9。这个系数已经被误改过一次（D-077）。**
> 曾据「中文 0.6–1.0 token/字」的通用经验判定 ÷1.6 是系统性低估，
> 改成 ×0.9；事后证明该判断作废——×0.9 比实测**保守 79%**，
> 会无谓地频繁触发压缩，每次都丢上下文。
> D-025 原话：「宁可压缩勤一点，不可撞上限」。

**高估是特性，不是缺陷**，但也不能无限高估（高估过头等于变相违反
D-039 的「绝不丢弃」）——上限由 `tests/test_estimate.py` 卡在 35%。
"""

