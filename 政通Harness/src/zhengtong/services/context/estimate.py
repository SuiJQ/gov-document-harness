#: 汉字除数。D-025 实测每字约 0.5 token，除 1.6 得 0.625，比实测高 24%。
#: **别改。** 误改记录见 D-077 与本文件顶部说明。
汉字除数: Final[float] = 1.6

#: 非汉字除数。英文/代码每 token 约 4 字符（精确 ÷4）；
#: 除 2 偏保守，方向与汉字侧一致。
非汉字除数: Final[float] = 2.0

#: 压缩触发阈值（D-025）。容量达到 85% 即兜底压缩。
触发比例: Final[float] = 0.85


def 估算文本(token数: str) -> int:
    """估算一段文本的 token 数。

    汉字与非汉字**分开算**再相加——用统一系数会在中英混排时失真：
    公文正文是中文，路径与英文术语是拉丁字符，两者每 token 的字符数不同。
    """
    汉字 = 0
    非汉字 = 0
    for 字 in token数:
        # CJK 统一表意文字与常用扩展区。
        # 用码位区间判定而非 `str.isalpha()`：后者对「Ω」「Ⅳ」也返回 True，
        # 而这些在公文里极少出现，混进汉字侧只会让估算偏保守——
        # 方向没错，但会把英文术语的字符算贵。
        if "一" <= 字 <= "鿿" or "㐀" <= 字 <= "䶿":
            汉字 += 1
        else:
            非汉字 += 1
    return int(汉字 / 汉字除数) + int(非汉字 / 非汉字除数)


def 触发阈值(上下文容量: int) -> int:
    """85% 阈值对应的 token 数。**向下取整**，宁可早触发。"""
    return int(上下文容量 * 触发比例)
