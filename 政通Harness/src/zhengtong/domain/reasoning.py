"""推理开关的探测结论（架构 §6.2）。

## 为什么这个类型住在 domain 而不是 adapters

**三个层都要碰它**：探测层产出它、编排层读它、装配根翻译它。
住在 `adapters/reasoning_probe.py` 会逼编排层 import 适配器（D-070 破防）；
塞进 `ports/llm.py` 又会让「端口」被迫携带一个它并不解释的业务结论。
故放 domain：探测层与编排层都是向下 import，两边都不破防。

## 为什么必须拆成五个状态而不是一个整数

早先的设计是 `可用写法: int`，**0 同时表示三件完全不同的事**：

| 实际情况 | 用户真正需要知道的 |
|---|---|
| 四种写法全败 → 推理强制开启、关不掉 | 成文更慢、额度更贵 |
| 基准请求就没有推理 → 该模型**不需要**关 | 什么也不用管，本来就不花钱 |
| 后端不回报 `reasoning_tokens` → **判不出来** | 探测手段不适用于这个服务 |

压成一个 0 之后，探测对第 2 种情况也说「关不掉推理，将按开启运行」——
**对一个本来就不推理的模型，这句话是假的**，
而且会跟着 `cli` 的处置建议再误导一次（「成文更慢、额度消耗更高」）。

这与 `ports.LlmProbe.探测结论` 用 `通过项/未测` 两组让「矛盾状态不可表示」
是同一条纪律（D-295/D-380 家族）：**一个字段承担多种语义，
就迟早会把其中一种说成另一种**。

## `-1` 契约：`-1` 是「后端不报推理用量」，不是「推理为 0」

`adapters/reasoning_probe._推理token` 在 `usage` 缺失时返回 `-1`，
其 docstring 写死了「**只有字段确实存在才参与判定**」。
早先调用方用 `基准推理 <= 0` 一网打尽，把 `-1` 当成了「不推理」——
**契约在调用处被违背**，docstring 警告的陷阱实现自己踩了。
故本文件把它做成独立状态（`无法判定`），不再依赖调用方记得特判。
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class 推理状态(StrEnum):
    """推理开关的实测状态。**五态**。

    ## 为什么 `无需关闭` 必须是独立的一态

    它既不是「关闭成功」也不是「关闭失败」，而是**根本不需要关闭**。
    混进成功里，用户会以为程序做了什么手脚；
    混进失败里，用户会为一个不用花钱的模型去换服务商。

    ## 为什么 `无结论` 也独立

    「还没探测过」与「探测过但判不出来」对用户的**行动建议不同**：
    前者只要跑一次 `--doctor`，后者是探测手段对该服务不适用。
    合并成一个 0 就只能永远说同一句话，其中一半是错的。
    """

    #: 实测出能关，且测出是第几种写法（1–4）。
    能关闭 = "能关闭"
    #: 基准请求就没有推理内容——该模型不生成推理，开关对它无意义。
    无需关闭 = "无需关闭"
    #: 基准有推理，四种写法全败（强制开启，关不掉）。
    关闭不了 = "关闭不了"
    #: 后端不回报推理用量，**判不出来**。这不是「关不掉」。
    无法判定 = "无法判定"
    #: 从未探测过，或落盘结论与当前模型对不上。
    无结论 = "无结论"


@dataclass(frozen=True, slots=True)
class 推理开关:
    """探测结论 + 已翻译的关闭方案。**运行期只认这一个类型**。

    ## 为什么 `关闭字段` 与 `可用写法` 都在这里

    「怎么关」的知识住在适配层（`写法表` 的四个后端烙印），
    编排层不认识「写法序号」这个概念（D-070 要求唯一装配点）。
    故由**装配根**把序号翻译成请求体字段再传下来。

    两个字段并存不是冗余：`可用写法` 给**人和日志**看（说明第几种生效），
    `关闭字段` 给**请求**用。运行期不需要序号，只需要字段——
    但序号丢了，用户界面就只能说「能关」而说不出「用第几种关的」。
    """

    状态: 推理状态 = 推理状态.无结论
    #: 已翻译好的关闭方案。**空元组 = 不附加任何字段**。
    关闭字段: tuple[tuple[str, object], ...] = ()
    #: 第 4 种写法的提示词前缀（`/no_think`）。它装不进请求体字段。
    提示前缀: str = ""
    #: 实测生效的写法序号（1–4），仅供显示。`0` 表示没有可用写法。
    可用写法: int = 0

    @property
    def 能关闭(self) -> bool:
        """能不能真的关掉。**只有实测出写法才算**。"""
        return self.状态 is 推理状态.能关闭

    def 说明(self) -> str:
        """给用户看的一句话。**五个状态五句话，不共用分支**。"""
        match self.状态:
            case 推理状态.能关闭:
                return f"推理可关闭（第 {self.可用写法} 种写法生效）"
            case 推理状态.无需关闭:
                return "此模型不生成推理内容，无需关闭推理"
            case 推理状态.关闭不了:
                return "此服务关不掉推理，将按开启运行"
            case 推理状态.无法判定:
                return "此服务不回报推理用量，无法判定推理开关"
            case 推理状态.无结论:
                return "未探测过推理开关，本次不做推理控制"


__all__ = ["推理开关", "推理状态"]
