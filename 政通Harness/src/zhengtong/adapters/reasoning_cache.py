"""推理开关结论的落盘与读取（D-380）。

## 为什么要有这个文件

`reasoning_probe` 能实测出「这个后端用第几种写法关推理」，
但结论此前**只变成一句中文显示给用户**就丢了。
而 `--doctor` 与实际写作文是**两个进程**——
不落盘，运行时永远拿不到「该用哪种写法」。

于是 `写法表` 里那四道关闭写法从未用于关闭任何一次请求：
测了、报告了、用户看得懂，然后丢掉。

## 为什么不干脆运行时自己探测

探测最多发 4 次请求，每次模型往返几十秒。
挂在每次启动上等于凭空加一两分钟，
而这四道写法的答案在同一个模型 + 同一个端点上**不会变**。

故：**doctor 测一次落盘，运行时读**。换个模型必须重测——
与 D-025「分词比不是通用值」同款纪律。

## 落盘的是**状态**，不是只有写法序号

早先只存 `{"模型": ..., "写法": 0}`，而 `写法=0` 同时表示
「关不掉」「模型本来就不推理」「判不出来」三件事——
运行时读回一个 0，**分不清该对用户说什么**，于是统一说成「关不掉」。
现在连 `状态` 一起存，运行时才拿得到正确的提示（D-384 家族：
字段填好被丢掉 / 一个值承载多种语义）。

## 零风险保证

文件不存在、状态为「关闭不了」「无需关闭」「无法判定」、
模型对不上——**任一情况都不附加任何字段**，
请求体与从前**逐字节相同**（D-004：不拼接不改写）。

所以这个功能在最坏情况下等于「没做」，
不会把任何一个能用的端点弄坏。

**注意「零风险」不等于「零误导」**：静默不附加字段意味着
OFF 档（咨询/Flash）会照常付推理的钱，故运行期必须**提示**一次，
见 `domain.reasoning.推理开关` 与 `App.推理提示`。
"""

from __future__ import annotations

import json
from pathlib import Path

from ..domain.reasoning import 推理开关, 推理状态

__all__ = ["关闭方案", "写推理结论", "读推理结论"]


def 写推理结论(系统目录: Path, *, 模型: str, 结论: 推理开关) -> None:
    """把探测结论写进 `system/reasoning.json`。

    ## 为什么必须连模型名一起存

    写法是**后端烙印**：同一个程序换一家服务商、换一个模型，
    生效的写法就可能不同。若只存写法序号，换模型后程序会拿着
    **上一种模型的写法**去请求——而错误的写法字段通常被服务端
    **静默忽略**，于是用户以为推理关掉了，实际还在推理并计费。

    故存模型名，读的时候**对不上就当没有结论**。

    **写失败不得抛**——探测已经成功了，
    落盘只是为了让运行时少发几次请求。
    为了存一个提速用的缓存而让 `--doctor` 失败，是本末倒置。
    """
    路径 = 系统目录 / "reasoning.json"
    try:
        系统目录.mkdir(parents=True, exist_ok=True)
        路径.write_text(
            json.dumps(
                {
                    "模型": 模型,
                    "写法": int(结论.可用写法),
                    "状态": 结论.状态.value,
                },
                ensure_ascii=False,
            ),
            encoding="utf-8",
        )
    except OSError:
        # 目录只读、磁盘满、权限不足——都不影响本次探测结论已呈现给用户。
        return


def 读推理结论(系统目录: Path, *, 模型: str) -> 推理开关:
    """读出该模型的探测结论。**读不到或对不上就返回 `无结论`**，不抛。

    ## 为什么不抛

    这份文件是**提速用的缓存，不是配置**。
    读不到就退化成「不控制推理」，那本来就是调用前的老行为。
    让一个可选缓存变成启动失败点，是把优化变成了故障源。

    ## 为什么返回类型而不是 `int`

    早先返回写法序号，`0` 同时表示「没文件」「模型对不上」
    「关不掉」「无需关闭」「判不出来」——五种情形一个值，
    调用方无从给用户一句准确的话。
    现在返回带 `状态` 的类型，**「未探测过」与「探测过但关不掉」
    才能被说成两句不同的话**。

    ## 状态字段缺失（老版本落盘）怎么办

    老文件只有 `{"模型", "写法"}`。此时**从写法序号反推状态**：
    写法 1–4 → `能关闭`，写法 0 → `关闭不了`。
    反推在「老文件其实是无需关闭」时会失真——但那只是
    少一句提示文案，不会误加字段，故接受。
    """
    路径 = 系统目录 / "reasoning.json"
    无 = 推理开关()
    try:
        原始 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return 无
    if not isinstance(原始, dict):
        return 无
    if 原始.get("模型") != 模型:
        # **模型对不上就当没有结论**：写法是后端烙印（D-380 的字段注释）。
        return 无
    写法 = 原始.get("写法")
    if not isinstance(写法, int) or 写法 < 0:
        return 无
    状态 = 原始.get("状态")
    if isinstance(状态, str):
        try:
            结论 = 推理状态(状态)
        except ValueError:
            结论 = 推理状态.关闭不了 if 写法 else 推理状态.无结论
    else:
        # **老文件没有状态字段**：按写法序号反推。
        结论 = 推理状态.能关闭 if 写法 > 0 else 推理状态.关闭不了
    if 结论 is not 推理状态.能关闭:
        # 非「能关闭」时**序号一律清零**：状态与序号自相矛盾时，
        # 宁可丢掉序号也不能让它拼出「第 0 种写法生效」。
        写法 = 0
    return 推理开关(状态=结论, 可用写法=写法)


def 关闭方案(序号: int) -> tuple[tuple[tuple[str, object], ...], str]:
    """把写法序号翻译成「怎么关」。

    返回 `(请求体字段, 提示词前缀)`。

    ## 为什么拆成两个返回值

    `写法表` 的第 4 种是**提示词前缀 `/no_think`**，不是请求体字段——
    它根本装不进 `LlmRequest.额外字段`。
    硬塞进去的话会给服务端发一个它不认识的字段，
    而服务端通常**静默忽略**，于是「以为关掉了、实际没关」。

    故两种机制必须分开表达。

    ## 为什么在适配层翻译而不是编排层

    `写法表` 住在 `adapters/reasoning_probe`。
    编排层 import 适配器会破掉 D-070（唯一装配点）。
    故由装配根调用本函数，把结果当**值**传下去——
    编排层自始至终只见到两个普通值，不认识「写法」这个概念。
    """
    from .reasoning_probe import 写法表

    if 序号 < 1 or 序号 > len(写法表):
        return ((), "")
    # **按下标取而不是解包**：`写法表` 三元组里只用到第 0、1 项，
    # 解包第三项会触发 RUF059（未使用的解包变量）。
    项 = 写法表[序号 - 1]
    字段 = 项[1]
    if 字段:
        return (字段, "")
    # 第 4 种：没有请求体字段，靠**提示词前缀**——而前缀写在**名称**里
    # （`"提示词前缀 /no_think"`），不在说明里（说明是「llama.cpp 老版、Qwen 模板」）。
    # 先前从说明里正则提取，取到的是空——于是前缀写法**翻译出来是空的**，
    # 装上了等于没装。
    import re

    命中 = re.search(r"/[A-Za-z_]+", 项[0])
    return ((), 命中.group(0)) if 命中 else ((), "")
