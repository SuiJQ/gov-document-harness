"""问答闸门：模型提问 → 用户回答。

## 为什么单独一个类

编排器**没有任何暂停/等待机制**（`threading.Event`/`Condition` 零命中），
所以硬停车不可能实现成「挂起编排器等用户」——
只能让**提问的一方阻塞**，直到另一线程把答案送来。

worker 线程被占住，**而这正好符合硬停车的语义**：车停了就是停了。

## 为什么不放在 orchestration 层

`presentation/` 按分层判据**不 import `orchestration`**
（`事件桥接` 就是用 `编排器: object` 避开的）。

闸门要同时被编排侧（提问）和界面侧（答复）拿到，
放 `presentation/` 与 `事件桥接` 同层，
由 `app.py` 装配根把同一个实例递给两边——**和桥接层一个套路**。

## 提问不在事件流里

用户已拍板「30 种死事件不补」，而 `USER_QUESTION_RAISED` 正在其中。

**所以界面只能靠闸门本身知道「有个问题在等」，没有事件可听。**
这是设计的必然，不是缺陷——但必须写在这里，
否则后人会在事件流里找那个不存在的事件，找不到就以为接缝断了。
"""

from __future__ import annotations

import threading
from collections.abc import Callable

#: 默认无应答等待上限（秒）。
#:
#: **强制等待不等于永久挂死。**「强制等待」的本意是
#: **不许带着空字段继续**（D-007），不是让用户被永久挂住。
#:
#: `--run` 无界面模式下没有人回答，
#: 没有上限的强制等待就是一个**永久挂起的进程**——
#: 用户不知道它在等什么、等多久。
#:
#: 30 分钟：一次完整的公文写作本该几分钟到几十分钟，
#: 超过这个数基本是用户走开了或界面已经关了。
默认超时秒 = 1800.0

#: 答复方签名：收到字段元组，返回用户答案字符串。
答复函数 = Callable[[tuple[dict[str, object], ...]], str]


class 问答闸门:
    """提问方阻塞等答复。

    ## 线程模型

    - **提问方**（编排 worker 线程）调 `问()`，**阻塞**
    - **答复方**（界面线程）调 `挂答复()` 注册回调，之后由界面负责调用

    用 `Event` 而不是 `Condition`：一问一答，
    没有「谁先到谁先得」的需要，Event 足够且不容易写错。

    ## 拒绝「无人应答就返回空串」

    **那是最危险的一种失败。**返回空串，模型会读成
    「用户没有意见」，于是按自己的猜测往下写——
    而 D-007 禁止编造。

    故无人应答（含答复为空串）一律走**超时失败**，
    **不静默、不降级、不跳过**。
    """

    __slots__ = ("_答复", "_超时秒", "_锁")

    def __init__(self, *, 超时秒: float = 默认超时秒) -> None:
        self._答复: 答复函数 | None = None
        self._锁 = threading.Lock()
        self._超时秒 = 超时秒

    def 挂答复(self, 答复: 答复函数 | None) -> None:
        """注册答复方（界面侧）。传 `None` 取消——**等于没人应答**。"""
        with self._锁:
            self._答复 = 答复

    def 有答复方(self) -> bool:
        with self._锁:
            return self._答复 is not None

    def 问(self, 字段: tuple[dict[str, object], ...]) -> str:
        """提问并**阻塞等待**答复。

        ## 答复方还没挂上时，**照样等**

        我第一版在「没挂答复方」时**立刻失败**，
        判据 `test_无人应答时阻塞而非立即返回` 把它抓了出来：
        **那不是强制等待，是立刻放弃。**

        为什么仍要等：界面有可能在运行启动**之后**才注册答复方
        （TUI 先起 App、后挂表单是常见写法）。
        立刻失败会在那个竞态里把一次合法的提问判死。

        **两种无人应答都走同一条路：等到超时才失败。**

        ## 答复方抛异常时

        **不能让提问方永久挂住。**界面代码是会崩的。
        故异常照样交付给提问方（`raise` 传播），
        同时确保 Event 被 set——闸门不会卡在等待态。
        """
        到号 = threading.Event()
        结果: list[str] = []
        失败: list[BaseException] = []

        def 交付(文本: str) -> None:
            结果.append(文本)
            到号.set()

        def 交付失败(错: BaseException) -> None:
            失败.append(错)
            到号.set()

        with self._锁:
            答复 = self._答复

        if 答复 is not None:
            # **答复在闸门的锁外跑**：它可能要渲染界面、要等用户，
            # 期间不该阻塞别的提问方。
            def 跑答复() -> None:
                try:
                    文本 = 答复(字段)
                except BaseException as 错:  # 界面代码会崩
                    交付失败(错)
                    return
                if not isinstance(文本, str) or not 文本.strip():
                    # **空答复等于没人应答**（见类文档）
                    交付失败(TimeoutError(self._超时文案()))
                    return
                交付(文本)

            threading.Thread(target=跑答复, daemon=True, name="问答闸门-答复").start()

        # **没有答复方也等**：见上面「答复方还没挂上时，照样等」。
        if not 到号.wait(self._超时秒):
            raise TimeoutError(self._超时文案())

        if 失败:
            raise 失败[0]
        return 结果[0]

    def _超时文案(self) -> str:
        return (
            f"等待用户回答超时（{self._超时秒:g} 秒）。"
            "程序**拒绝**在无人回答的情况下继续——"
            "带着空字段往下走会编造事实（D-007）。"
            "请在交互界面下重新运行以回答提问，"
            "或改用「咨询」档（该档不问用户）。"
        )
